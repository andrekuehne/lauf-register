-- Gender is stored per Participant; the Division is no longer stored (it follows
-- from the number of Participants and their Genders). Registrations stored so
-- far are test data without Gender, so both tables are rebuilt empty.
DROP TABLE participants;
DROP TABLE registrations;

-- Registration numbers count separately: singles from 1, Pairs from 1001.
-- Both counters only ever count up, so a number shown on a phone is never given out twice.
-- The one deliberate exception is the reset below: every Registration is deleted here,
-- so no number handed out so far belongs to anyone any more.
ALTER TABLE races RENAME COLUMN last_registration_number TO last_single_number;
ALTER TABLE races ADD COLUMN last_pair_number INTEGER NOT NULL DEFAULT 0;
UPDATE races SET last_single_number = 0;

-- A Registration: one submitted sign-up for one Category within one Race (see GLOSSARY.md).
CREATE TABLE registrations (
  id INTEGER PRIMARY KEY,
  race_id INTEGER NOT NULL REFERENCES races (id) ON DELETE CASCADE,
  -- Registration number (also the StartNr in RaceResult): singles 1…, Pairs 1001….
  number INTEGER NOT NULL,
  -- Minutes: 30 or 60.
  duration INTEGER NOT NULL,
  -- Generated by the browser per Registration flow; a repeated submit returns the stored Registration.
  attempt_id TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
  UNIQUE (race_id, number),
  UNIQUE (race_id, attempt_id)
);

-- A Participant: one person on a Registration, in entered order.
CREATE TABLE participants (
  id INTEGER PRIMARY KEY,
  registration_id INTEGER NOT NULL REFERENCES registrations (id) ON DELETE CASCADE,
  -- 1, or 2 for the second person of a Pair.
  slot INTEGER NOT NULL CHECK (slot IN (1, 2)),
  gender TEXT NOT NULL CHECK (gender IN ('F', 'M')),
  -- One of the fixed Titles (src/domain/categories.ts).
  title TEXT NOT NULL CHECK (title IN ('none', 'dr')),
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  birth_year INTEGER NOT NULL,
  -- NULL when no club was given.
  club TEXT,
  UNIQUE (registration_id, slot)
);
