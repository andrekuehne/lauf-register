// Bundles the browser flow (src/client/flow.ts) for ~iOS 12 / Android 8
// browsers and writes it as a string module the Worker inlines into the page.
// Runs before `wrangler dev`/`deploy` (wrangler.jsonc build.command), tests and typecheck.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

const result = await build({
  entryPoints: ["src/client/flow.ts"],
  bundle: true,
  minify: true,
  format: "iife",
  target: ["safari12", "chrome61"],
  legalComments: "none",
  write: false,
});

const js = result.outputFiles[0].text.replace(/<\/(script)/gi, "<\\/$1");
const out = "src/generated/flow-bundle.ts";
const content = `// Generated by scripts/build-client.mjs. Do not edit.\nexport const flowBundle = ${JSON.stringify(js)};\n`;
// Only write on change: wrangler dev watches src/, so rewriting identical output would loop.
const previous = await readFile(out, "utf8").catch(() => "");
if (previous !== content) {
  await mkdir("src/generated", { recursive: true });
  await writeFile(out, content);
}
console.log(`flow bundle: ${(js.length / 1024).toFixed(1)} KiB`);
