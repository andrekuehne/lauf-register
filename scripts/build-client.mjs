// Bundles the browser scripts (src/client/) for ~iOS 12 / Android 8 browsers
// and writes each as a string module the Worker inlines into its pages:
// the registration flow, the QR layer, the admin pages' confirmation dialogs, and
// the search on a Race's admin page.
// Runs before `wrangler dev`/`deploy` (wrangler.jsonc build.command), tests and typecheck.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

const BUNDLES = [
  { entry: "src/client/flow.ts", out: "src/generated/flow-bundle.ts", name: "flowBundle" },
  { entry: "src/client/qr-layer.ts", out: "src/generated/qr-layer-bundle.ts", name: "qrLayerBundle" },
  { entry: "src/client/confirm.ts", out: "src/generated/confirm-bundle.ts", name: "confirmBundle" },
  { entry: "src/client/race-search.ts", out: "src/generated/race-search-bundle.ts", name: "raceSearchBundle" },
];

await mkdir("src/generated", { recursive: true });
for (const bundle of BUNDLES) {
  const result = await build({
    entryPoints: [bundle.entry],
    bundle: true,
    minify: true,
    format: "iife",
    target: ["safari12", "chrome61"],
    legalComments: "none",
    write: false,
  });

  const js = result.outputFiles[0].text.replace(/<\/(script)/gi, "<\\/$1");
  const content = `// Generated by scripts/build-client.mjs. Do not edit.\nexport const ${bundle.name} = ${JSON.stringify(js)};\n`;
  // Only write on change: wrangler dev watches src/, so rewriting identical output would loop.
  const previous = await readFile(bundle.out, "utf8").catch(() => "");
  if (previous !== content) await writeFile(bundle.out, content);
  console.log(`${bundle.name}: ${(js.length / 1024).toFixed(1)} KiB`);
}
